const SELF_FAREWELL = "попрощайся сам одной короткой фразой, без «записал вас», без обещаний и без нового предложения встречи";
const LAST_REPLY = `одна-две фразы без вопроса, подтверждённый пересказ целиком не повторяй`;
const APP_CLOSES =
  "твой текст в этом ходе до человека не дойдёт. Если человек в последней реплике задал вопрос, ответ на него передай в поле answer у finish_dialog";

/** Кто прощается с человеком при каждом исходе: прощание приложения уходит только при agreed. */
export function lastReplyFarewellRule(farewellMessage: string): string {
  const farewell = farewellMessage.trim();
  return farewell
    ? `Исход agreed: человек получит прощальное сообщение «${farewell}», ${APP_CLOSES}; в answer не противоречь прощанию. ` +
        `Исход declined или left: прощального сообщения не будет, ${SELF_FAREWELL}.`
    : `Последний ответ: ${LAST_REPLY}, попрощайся в нём. При исходе declined или left ${SELF_FAREWELL}.`;
}

/** Правило последнего ответа для уже известного исхода: его возвращает finish_dialog. */
export function lastReplyRule(farewellMessage: string, outcome: DialogOutcome): string {
  const farewell = farewellMessage.trim();
  if (outcome !== "agreed") return `Прощального сообщения не будет. Напиши человеку последний ответ: ${SELF_FAREWELL}.`;
  return farewell
    ? `Человек получит ответ из answer, если он есть, и прощальное сообщение «${farewell}». Больше ничего не пиши: твой текст в этом ходе до человека не дойдёт.`
    : `Напиши человеку последний ответ: ${LAST_REPLY}, попрощайся в нём.`;
}
