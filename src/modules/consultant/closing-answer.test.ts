import { describe, expect, it } from "vitest";
import { answerWithoutFarewellRepeats } from "./closing-answer";

describe("ответ перед прощанием без повторов прощания", () => {
  it("выкидывает фразу, которая пересказывает прощание: кто, как и когда свяжется", () => {
    const farewell =
      "Спасибо, что поделился! Передам коучу, что ты хочешь встретиться, и он напишет тебе сюда, чтобы договориться о времени. До связи!";
    expect(
      answerWithoutFarewellRepeats("Коуч сам напишет тебе сюда, чтобы договориться о времени встречи. Тебе писать никуда не нужно.", farewell),
    ).toBe("Тебе писать никуда не нужно.");
  });

  it("выкидывает повторяющую часть фразы после тире и оставляет сам ответ, в том числе «эксперт уточнит»", () => {
    const farewell = "Спасибо, что рассказали! Передам Ольге — она напишет вам здесь, чтобы договориться о пробном уроке. До связи!";
    expect(
      answerWithoutFarewellRepeats(
        "Записываться никуда не нужно — Ольга сама напишет вам здесь и договорится об удобном вечернем времени.",
        farewell,
      ),
    ).toBe("Записываться никуда не нужно.");
    expect(
      answerWithoutFarewellRepeats(
        "Ничего особенного готовить не нужно — просто приходите с настроением поговорить. Про семь вечера Ольга уточнит, когда напишет вам здесь.",
        farewell,
      ),
    ).toBe("Ничего особенного готовить не нужно — просто приходите с настроением поговорить. Про семь вечера Ольга уточнит, когда напишет вам здесь.");
  });

  it("начало фразы пересказывает прощание, а остаток — обрывок со строчной буквы: фраза уходит целиком (eval 21.10: «уточнит сама.»)", () => {
    const farewell = "Отлично! Ольга свяжется с вами и договорится о времени пробного урока. До встречи!";
    expect(answerWithoutFarewellRepeats("Ольга свяжется с вами и договорится о времени, а как именно — уточнит сама.", farewell)).toBe("");
  });

  it("не трогает короткий ответ, где с прощанием совпало одно слово", () => {
    const farewell = "Отлично! Передам эксперту — он свяжется с вами, чтобы договориться о разборе. Спасибо, что заглянули!";
    expect(
      answerWithoutFarewellRepeats(
        "Да, разбор бесплатный — это его условие, платить за него не нужно. Остальное по формату уточнит Тимур.",
        farewell,
      ),
    ).toBe("Да, разбор бесплатный — это его условие, платить за него не нужно. Остальное по формату уточнит Тимур.");
  });

  it("общие слова с прощанием вразброс — не повтор: ответ после «беру» доходит целиком (случай Светы)", () => {
    const farewell = "Отлично! Вот ссылка на интенсив: https://pay.example.com/intensiv — там подробности и оплата. До встречи на первой встрече!";
    const answer = "Дату первой встречи и получится ли оплатить с телефона — уточнит Дмитрий.";
    expect(answerWithoutFarewellRepeats(answer, farewell)).toBe(answer);
  });

  it("убирает благодарность", () => {
    expect(answerWithoutFarewellRepeats("Спасибо за доверие! Созвон бесплатный.", "До встречи!")).toBe("Созвон бесплатный.");
  });

  it("ответ, целиком повторяющий прощание, становится пустым", () => {
    const farewell = "Передам Кириллу, и он свяжется с вами, чтобы договориться о времени.";
    expect(answerWithoutFarewellRepeats("Кирилл свяжется с вами, чтобы договориться о времени.", farewell)).toBe("");
  });

  it("настоящий ответ на вопрос не трогает", () => {
    const farewell = "Спасибо! Передам бухгалтеру — он напишет вам и договоритесь о времени. Хорошего дня!";
    expect(answerWithoutFarewellRepeats("Марафон стоит 12 000 ₽, сам созвон — бесплатный.", farewell)).toBe(
      "Марафон стоит 12 000 ₽, сам созвон — бесплатный.",
    );
    expect(answerWithoutFarewellRepeats("  ", farewell)).toBe("");
  });
});
