import { describe, expect, it } from "vitest";
import { FIRST_MESSAGE_RULE } from "./instruction";

// Судья eval 19.10: молчуну — меню «1 — … 2 — …» в каждом касании и «домашние задания» («пришлите четыре цифры»)
describe("правило «пишешь первым»", () => {
  it("лестница прежняя: идея → выбор цифрой → готовый текст за человека (не «сделаю за вас» работу сервиса)", () => {
    expect(FIRST_MESSAGE_RULE).toMatch(/одной цифрой/);
    expect(FIRST_MESSAGE_RULE).toMatch(/сам напиши за человека готовый текст/);
  });

  it("сообщение первым не продаёт: ни платного продукта, ни цены, ни ссылки на оплату, ни сроков набора — если хвост прямо не разрешил (eval 21.10, марафон: 8 касаний, ссылка ×2)", () => {
    expect(FIRST_MESSAGE_RULE).toMatch(/сообщение первым не продаёт[^\n]*цену[^\n]*ссылку на оплату[^\n]*набор закрывается/i);
    expect(FIRST_MESSAGE_RULE).toMatch(/только если в конце запроса прямо сказано, что в этом сообщении можно/i);
    expect(FIRST_MESSAGE_RULE).toMatch(/шаг эксперта[^\n]*один раз за все сообщения первым/i);
  });

  it("выбор цифрой — один раз за разговор, а не в каждом касании", () => {
    expect(FIRST_MESSAGE_RULE).toMatch(/[Вв]ыбор цифрой — один раз за весь разговор/);
  });

  it("заданий молчащему не даёт", () => {
    expect(FIRST_MESSAGE_RULE).toMatch(/[Нн]е давай заданий/);
  });

  it("пустые «вы тут?» по-прежнему нельзя", () => {
    expect(FIRST_MESSAGE_RULE).toMatch(/«вы тут\?»/);
  });
});
