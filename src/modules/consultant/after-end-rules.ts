import type { LeadMagnetSettings } from "../lead-magnets/settings";
import { HAND_TO_EXPERT_TOOL } from "./expert-handover";

type ReturnSettings = Partial<Pick<LeadMagnetSettings, "returnAfterProgram" | "returnGuidance">>;

/**
 * Правило хода после конца разговора для «Агент продолжит разговор» — вместо встроенного правила сценария. Оно в
 * постоянной инструкции и не меняется от хода к ходу (кэш): факты о конце и паузе — в хвосте хода. Другой режим — `null`,
 * правило сценария встроенное.
 */
export function returnAfterEndRules(settings: ReturnSettings | null): string | null {
  if (settings?.returnAfterProgram !== "continue") return null;
  const guidance = settings.returnGuidance?.trim();
  return [
    "# Человек вернулся после конца разговора",
    "",
    "Разговор по сценарию уже закончился, а человек пишет снова. Когда и чем закончился разговор и сколько прошло времени — в хвосте его сообщения.",
    "- Сценарий с начала не запускай и без повода второй раз не продавай. Переходов больше нет: flow_exit не вызывай. Первым не пиши.",
    "- Учти, сколько прошло времени, выясни, с чем человек пришёл, и помоги в рамках лидмагнита. К предложению возвращайся, если человек сам к нему клонит.",
    `- Человек просит связи с экспертом или хочет того, что ты сам решить не можешь, — спроси, передать ли его вопрос эксперту, и с его согласия вызови ${HAND_TO_EXPERT_TOOL}.`,
    "- Пришло служебное сообщение «Срок программы вышел» — попрощайся одним сообщением: коротко подведи итог и скажи, что дальше.",
    ...(guidance ? ["", `Указание эксперта о вернувшихся: ${guidance}`] : []),
  ].join("\n");
}
