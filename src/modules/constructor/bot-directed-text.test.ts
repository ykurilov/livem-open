import { describe, expect, it } from "vitest";
import recorded from "./recorded/farewells.json";
import { assistantHandoffIn, botDirectionIn } from "./bot-directed-text";

describe("указание консультанту вместо текста для человека", () => {
  it("находит: «попрощайся», «порадуйся», «поблагодари», «скажи» в начале фразы, «если человек»", () => {
    const directions = [
      "Коротко попрощайся: порадуйся, что человек придёт на занятие, и напомни, что по ссылке он сам выберет удобные день и время. Если человек отказался — спокойно попрощайся, без уговоров и без «если что, пишите».",
      "Поблагодари за разговор и пожелай хорошего дня.",
      "Отлично! Скажи, что Анна напишет вечером.",
      "Тепло попрощайся и напомни про ссылку.",
      "Если человек согласился, дай ссылку на запись.",
    ];
    for (const text of directions) expect(botDirectionIn(text), text).not.toBeNull();
    expect(botDirectionIn(directions[0]!)).toBe("Коротко попрощайся");
  });

  it("не трогает настоящие прощания из прогонов, в том числе «напишите», «приходите» и «напиши сюда» на «ты»", () => {
    for (const text of [...recorded.farewells, "Если что-то поменяется — просто напиши сюда.", "Записал тебя. Скажите, если планы изменятся."])
      expect(botDirectionIn(text), text).toBeNull();
  });
});

describe("прощание, где помощник «передал» что-то эксперту", () => {
  it("находит «Передал Кириллу», «Всё передал эксперту», «Я передам», «Передаю» во всех записанных прощаниях такого вида", () => {
    expect(recorded.handoffs.length).toBeGreaterThan(0);
    for (const text of recorded.handoffs) expect(assistantHandoffIn(text), text).not.toBeNull();
    expect(assistantHandoffIn("Отлично! Всё передал эксперту: она напишет вам и подтвердит время. До встречи!")).toBe("передал");
  });

  it("не трогает остальные записанные прощания и просьбы к человеку «передайте», «можете передать»", () => {
    const others = [
      "Передайте Анне привет, она будет рада!",
      "Можете передать ссылку подруге.",
      // Ревью 21.10: не первое лицо помощника про передачу эксперту
      "Отлично! Анна передала привет и ждёт вас на занятии.",
      "Спасибо, что передали отзыв! До встречи.",
      "Не передам никому ваши данные — всё останется здесь. До встречи!",
    ];
    for (const text of [...recorded.farewells, ...others])
      expect(assistantHandoffIn(text), text).toBeNull();
  });
});
