// Прощание уходит человеку дословно (eval 19.10, normal-yoga: «Коротко попрощайся: порадуйся…»). Указание консультанту
// узнаётся по узкому списку: глагол на «ты», обращённый к боту, в начале фразы, или «если человек» — о человеке в третьем лице.
// В настоящих прощаниях повелительное тоже бывает, но к человеку («напишите», «приходите», «напиши сюда»): его не трогаем.

const BOT_VERBS = ["попрощайся", "порадуйся", "поблагодари", "напомни", "пожелай", "скажи", "сообщи", "упомяни", "подведи", "заверши"];
const MANNER = ["коротко", "кратко", "тепло", "спокойно", "вежливо", "дружелюбно", "по-доброму", "обязательно", "также", "ещё", "еще", "и"];

const NOT_LETTER = "(?![а-яё])";
const SENTENCE_START = "(?:^|[.!?…:;]\\s+|\\n\\s*|[—–]\\s+)";
const DIRECTION = new RegExp(
  `${SENTENCE_START}((?:(?:${MANNER.join("|")})\\s+)*(?:${BOT_VERBS.join("|")})${NOT_LETTER})|(если человек${NOT_LETTER})`,
  "iu",
);

// Помощник ничего не передаёт эксперту (eval 21.10: «Передал Кириллу», «Всё передал эксперту»): эксперт видит разговор сам.
// Ловится только первое лицо помощника: «передам/передал(а)/передаю» в начале фразы или после «я», «всё», «тогда»,
// после «я» в любом месте фразы, либо с получателем следом — «эксперту», «тренеру», «Кириллу». Не ловится: «передайте», «передали», «Анна передала
// привет» (подлежащее — не помощник), «Не передам никому» (отрицание).
const VERB = "([Пп]ередам|[Пп]ередал|[Пп]ередала|[Пп]ередаю)";
const LEAD_WORDS = "(?:я|мы|всё|все|тогда|уже|сразу|сейчас|и|это)";
const ROLES =
  "эксперту|тренеру|преподавателю|коучу|бухгалтеру|дизайнеру|психологу|менеджеру|консультанту|маркетологу|нутрициологу|инструктору|специалисту|автору|мастеру";
const AT_START = new RegExp(String.raw`${SENTENCE_START}(?:${LEAD_WORDS}\s+)*${VERB}${NOT_LETTER}`, "iu");
const TO_SOMEONE = new RegExp(
  String.raw`(?<![а-яё]не\s)(?<![А-ЯЁ][а-яё]+\s)(?<![а-яё])${VERB}${NOT_LETTER}(?:\s+[^\s.!?]+){0,3}?\s+(?:${ROLES}|[А-ЯЁ][а-яё]+(?:е|у|ю|и))${NOT_LETTER}`,
  "u",
);

const AFTER_I = new RegExp(String.raw`(?<![а-яё])[Яя]\s+(?:всё\s+|все\s+)?${VERB}${NOT_LETTER}`, "u");

/** «Передал Кириллу», «Всё передал эксперту», «Я передам» — помощник будто передаёт что-то эксперту; `null` — нет. */
export function assistantHandoffIn(text: string): string | null {
  return (AT_START.exec(text)?.[1] ?? AFTER_I.exec(text)?.[1] ?? TO_SOMEONE.exec(text)?.[1])?.toLowerCase() ?? null;
}

/** Указание консультанту в тексте для человека — его начало («Коротко попрощайся»); `null` — указаний нет. */
export function botDirectionIn(text: string): string | null {
  const match = DIRECTION.exec(text);
  if (!match) return null;
  const found = (match[1] ?? match[2])!;
  return found.charAt(0).toUpperCase() + found.slice(1);
}
