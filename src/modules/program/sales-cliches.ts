// Штампы продаж: заученные фразы из тренингов, нажим и фальшивая срочность.
// Ими пользуются инструкция консультанта (примеры «как нельзя») и проверки eval.

export interface SalesCliche {
  /** Как штамп называется в отчёте и в инструкции. */
  phrase: string;
  pattern: RegExp;
}

export const SALES_CLICHES: readonly SalesCliche[] = [
  { phrase: "по сравнению с чем", pattern: /по сравнению с чем/ },
  { phrase: "что вас останавливает", pattern: /что (?:вас|тебя) останавливает/ },
  { phrase: "что мешает принять решение", pattern: /что (?:вам |тебе )?мешает (?:принять решение|решиться)/ },
  { phrase: "если бы цена не была проблемой", pattern: /если бы (?:цена|деньги) не (?:была|были) проблемой|если отбросить (?:цену|деньги)/ },
  { phrase: "дорого — это сколько", pattern: /дорого\s*[—–-]?\s*это сколько/ },
  { phrase: "только сегодня", pattern: /только (?:сегодня|до конца дня|до полуночи)/ },
  { phrase: "осталось N мест", pattern: /осталось (?:всего |лишь |только )?(?:\d+|одно|два|три|пару|несколько) мест/ },
  { phrase: "места заканчиваются", pattern: /места (?:заканчиваются|на исходе)/ },
  { phrase: "предложение ограничено", pattern: /предложение ограничено/ },
  { phrase: "не упустите шанс", pattern: /не упусти(?:те)? (?:свой )?(?:шанс|возможность)/ },
  { phrase: "последний шанс", pattern: /последний шанс/ },
  { phrase: "успейте", pattern: /успейте|успей (?:купить|записаться|оплатить)/ },
  { phrase: "инвестиция в себя", pattern: /инвестици[яюи] в (?:себя|самого себя)/ },
  { phrase: "многие так думали, пока", pattern: /многие (?:так )?(?:думали|сомневались)[^.!?]*пока/ },
  { phrase: "вы не можете себе позволить не", pattern: /(?:не можете|не можешь) себе позволить не/ },
];

const normalized = (text: string) => text.toLowerCase().replaceAll("ё", "е");

/** Штампы, найденные в тексте, — по названию, без повторов. */
export function findSalesCliches(text: string): string[] {
  const plain = normalized(text);
  return SALES_CLICHES.filter((cliche) => cliche.pattern.test(plain)).map((cliche) => cliche.phrase);
}
