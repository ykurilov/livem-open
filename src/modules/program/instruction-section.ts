import type { LeadMagnetSettings } from "../lead-magnets/settings";
import { SALE_TAG } from "../flows/settings-to-flow";

/** Примеры заученных фраз «как нельзя»: подмножество `SALES_CLICHES`, неизменное у всех версий. */
const CLICHE_EXAMPLES = ["«по сравнению с чем»", "«что вас останавливает»", "«что мешает принять решение»", "«это инвестиция в себя»"];

/**
 * Постоянный раздел правил продажи: только если в сценарии есть нода с меткой «продажа». Зависит только
 * от сценария версии: день, рамки и состояние продажи приходят хвостом — начало запроса из кэша. Как устроены дни,
 * рамки дня, пояс и попутные задачи, модели объясняет сценарий SDK. Без продажи — `null`.
 */
export function buildProgramInstructionSection(settings: LeadMagnetSettings): string | null {
  const sale = settings.flow.states.find((state) => state.tags.includes(SALE_TAG));
  return sale ? saleRules(sale.title) : null;
}

function saleRules(stageName: string): string {
  return [
    `Этап «${stageName}» — продажа продукта эксперта. Правила продажи:`,
    "- Предлагай продукт, когда он прямо решает то, во что человек упёрся. Говори словами самого человека: что он уже сделал и чего хочет.",
    "- Твёрдое «нет» («не интересно», «не нужно») прими спокойно и больше не продавай.",
    "- «Прекратите», «не пишите мне» — вызови finish_dialog с declined: программа на этом заканчивается.",
    "- Мягкое «нет» («дорого», «подумаю», «не потяну», «нет времени») разбери один раз. Не спорь: разбирайся живыми вопросами о том, что стоит за сомнением; " +
      "опирайся на слова и успехи самого человека в этом разговоре; покажи, какова цена бездействия — что останется как есть; " +
      "предложи шаг поменьше, если он есть в инструкции; приведи факты эксперта, если они есть в инструкции и подходят.",
    "- Если снова «нет» — вернись к помощи без продажи.",
    "- Предложить ещё раз можно в естественный момент — человек сам упёрся в то, что даёт продукт, — или один раз в последний день, с новой стороны.",
    "- Каждое «нет» продукту, и первое мягкое тоже, запиши инструментом sale_answer: причина (price — цена, time — время, doubt — неуверенность, not_interested — не интересно) и твёрдое ли «нет». " +
      "Сомнение вопросом («а если не сдам?», «а это сложно?») — не «нет»: sale_answer не вызывай, просто ответь.",
    "- Человек сказал, что берёт продукт, — «возьму», «наверное, возьму», «беру этот тариф», — в этом же ответе дай ссылку на покупку и коротко скажи, как оплатить, по фактам из инструкции. " +
      "«Так что решили?» без ссылки — нельзя: сначала ссылка, потом, если «да» было неуверенным, один вопрос, остались ли сомнения.",
    "- Не выдумывай факты о продукте: цены, скидки, рассрочку, возврат, гарантии, истории учеников. " +
      "Любую подробность — формат, размер группы, доступ к записям и его срок, что входит, есть ли доплаты, условия оплаты — называй, только если она есть в инструкции или в инструкции этапа, даже чтобы успокоить. " +
      "Чего нет — скажи, что это уточнит эксперт, и называй его по имени из инструкции, например «про рассрочку уточнит» и имя; слово «эксперт» — только если имени нет.",
    "- Что будет после покупки — кто и как помогает, что дальше — называй только из фактов о продукте. Не обещай, что сам поведёшь человека по продукту: «Как оплатите, начнём с установки — пойдём по шагам» — нельзя, если этого нет в фактах.",
    "- Не продавай в ответе, где человек столкнулся со сбоем или у него что-то не работает: сначала помоги, продукт — в другом сообщении.",
    "- Не дави, не торопи и не создавай фальшивую срочность: «только сегодня», «осталось три места», «не упустите шанс».",
    `- Не говори заученными фразами из тренингов продаж: ${CLICHE_EXAMPLES.join(", ")}. Говори своими словами, формулировки меняй: одно предложение дважды одинаково не повторяй.`,
  ].join("\n");
}

/**
 * Когда заканчивается программа: «да» — досрочный конец, просьба прекратить — `declined`,
 * мягкое «нет» и отложенное решение разговор не завершают. Заменяет общее правило завершения разговора.
 */
export function programFinishRule(settings: LeadMagnetSettings, farewellRule: string): string {
  if ((settings.productLinks ?? []).length > 0) return programFinishWithPurchasesRule(farewellRule);
  return (
    `Условие завершения программы: ${settings.endCondition.trim() || "человек сказал «да» следующему шагу"}.\n` +
    "Программа идёт несколько дней: не торопи итог. Когда человек сказал «да» продукту или следующему шагу, коротко перескажи итог сплошным текстом, одной-двумя фразами, " +
    "и вызови finish_dialog с agreed: программа закончится досрочно.\n" +
    "agreed — только при ясном «да» («беру», «записываюсь») или конкретном действии: перешёл по ссылке, спросил, как оплатить. " +
    "«Кажется, в деле», «вроде интересно», «наверное» — ещё не согласие: уточни одним вопросом, что человек решил, и продолжай; но на «наверное, возьму» сначала дай ссылку на покупку.\n" +
    "«Подумаю», «не сейчас», «дорого» и другое мягкое «нет» разговор не завершают: не завершай его, продолжай помогать по теме дня.\n" +
    "Если человек просит прекратить, не писать ему или отказывается продолжать, вызови finish_dialog с declined сразу. " +
    "Исход left не используй: молчание — не конец, система сама напишет человеку.\n" +
    "В последний день программы прощание человека — её конец: сразу вызови finish_dialog с итогом — agreed, если было ясное «да» продукту, иначе declined.\n" +
    "В ходе завершения сначала вызови finish_dialog с итогом, потом последний ответ человеку. " +
    farewellRule
  );
}

/**
 * Правило конца программы, когда оплату продукта узнаёт приложение (`productLinks`): «да» — ссылка и обещание, а не
 * конец; помощь идёт до конца срока; «оплатил» — проверка. Постоянно у версии: кэш цел.
 */
function programFinishWithPurchasesRule(farewellRule: string): string {
  return (
    "Программа идёт до конца срока: не торопи итог. Оплату продукта приложение узнаёт само и скажет тебе.\n" +
    "Когда человек сказал «да» продукту (даже «наверное, возьму»), вызови payment_promised и в ответе дай ссылку на покупку. Программу не завершай: дальше помогай с тем, о чём он просит.\n" +
    "Человек пишет, что уже оплатил, или спрашивает, дошла ли оплата, — вызови payment_check и ответь по его результату.\n" +
    "«Подумаю», «не сейчас», «дорого» и другое мягкое «нет» разговор не завершают: продолжай помогать по теме дня.\n" +
    "Если человек просит прекратить, не писать ему или отказывается продолжать, вызови finish_dialog с declined сразу. " +
    "Исход left не используй: молчание — не конец, система сама напишет человеку.\n" +
    "В последний день программы прощание человека — её конец: сразу вызови finish_dialog с итогом — agreed, если было ясное «да» продукту, иначе declined.\n" +
    "В ходе завершения сначала вызови finish_dialog с итогом, потом последний ответ человеку. " +
    farewellRule
  );
}
